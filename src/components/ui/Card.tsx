import * as React from "react"
import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { glass?: boolean; hoverEffect?: boolean }
>(({ className, glass = false, hoverEffect = false, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-2xl border bg-card text-card-foreground shadow-sm transition-all duration-300 relative overflow-hidden",
      glass && "glass",
      hoverEffect && "hover:-translate-y-1 hover:shadow-2xl hover:border-white/20",
      className
    )}
    {...props}
  >
    <div className="relative z-10 h-full w-full">
      {props.children}
    </div>
    {/* Subtle inner top highlight for all premium cards */}
    <div className="absolute inset-0 rounded-2xl pointer-events-none border border-white/5 opacity-50 mix-blend-overlay z-20" />
  </div>
))
Card.displayName = "Card"

